CREATE TABLE members (
    member_id            VARCHAR(5)   PRIMARY KEY,
    name                 VARCHAR(120) NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    can_open_sub_account BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT members_member_id_format CHECK (member_id ~ '^[0-9]{5}$')
);

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id      VARCHAR(5)     NOT NULL REFERENCES members (member_id),
    account_number VARCHAR(32)    NOT NULL,
    account_type   VARCHAR(80)    NOT NULL,
    balance        NUMERIC(14, 2) NOT NULL,
    opened_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT accounts_account_number_key UNIQUE (account_number),
    CONSTRAINT accounts_balance_non_negative CHECK (balance >= 0)
);

CREATE INDEX accounts_member_id_idx ON accounts (member_id);

CREATE TABLE audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       UUID         NOT NULL,
    event_type     VARCHAR(40)  NOT NULL,
    operator_id    VARCHAR(40),
    member_id      VARCHAR(5)   REFERENCES members (member_id),
    account_number VARCHAR(32),
    message        VARCHAR(500) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT audit_events_event_id_key UNIQUE (event_id)
);
